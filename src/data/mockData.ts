// Helper to generate realistic starting candlestick bars for any asset
export function generateCandlesForAsset(basePrice: number, count: number = 60, volatility: number = 0.003): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const intervalMs = 60000; // 1 minute per candle
  let currentPrice = basePrice * (1 - volatility * (count / 2));

  for (let i = count; i >= 0; i--) {
    const time = now - i * intervalMs;
    const change = (Math.random() - 0.49) * (volatility * currentPrice);
    const open = currentPrice;
    const close = open + change;
    const high = Math.max(open, close) + Math.random() * (volatility * 0.7 * currentPrice);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.7 * currentPrice);
    const volume = Math.floor(5000 + Math.random() * 25000);

    candles.push({
      time,
      open,
      high,
      low,
      close,
      volume,
    });

    currentPrice = close;
  }

  return candles;
}
